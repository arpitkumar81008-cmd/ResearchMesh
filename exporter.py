"""
exporter.py — Convert a ResearchReport + SourceReferences into export formats.

Public API
----------
  to_markdown(report, sources) -> str   Publication-ready Markdown document.
  to_json(report, sources)     -> str   Full structured JSON bundle.
"""
from __future__ import annotations

import json
from typing import List

from models import ResearchReport, SourceReference

# Emoji badges per claim status
_STATUS_EMOJI = {
    "Corroborated": "✅",
    "Conflicting": "⚠️",
    "Single-Source": "🔵",
}


def to_markdown(report: ResearchReport, sources: List[SourceReference]) -> str:
    """
    Render the ResearchReport as a clean, publication-ready Markdown document.

    Sections:
      1. Header & question
      2. Executive Summary (with inline citations)
      3. Claims & Evidence (grouped by status, conflict callouts)
      4. Research Timeline (date-sorted table)
      5. Follow-Up Questions
      6. Bibliography (numbered, with URLs and retrieval method)
    """
    lines: List[str] = []

    # ── Header ──────────────────────────────────────────────────────────────
    lines += [
        "# ResearchMesh — Evidence-Backed Research Report",
        "",
        f"**Research Question:**  ",
        f"{report.question}",
        "",
        "---",
        "",
    ]

    # ── Executive Summary ────────────────────────────────────────────────────
    lines += [
        "## Executive Summary",
        "",
        report.executive_summary,
        "",
        "---",
        "",
    ]

    # ── Claims & Evidence ────────────────────────────────────────────────────
    lines += [
        "## Claims & Evidence",
        "",
    ]

    # Group claims: Corroborated → Single-Source → Conflicting (most notable last)
    def _sort_key(c):
        order = {"Corroborated": 0, "Single-Source": 1, "Conflicting": 2}
        return order.get(c.status, 99)

    for claim in sorted(report.claims, key=_sort_key):
        emoji = _STATUS_EMOJI.get(claim.status, "")
        lines += [
            f"### {emoji} {claim.topic}",
            "",
            f"**Status:** `{claim.status}`",
            "",
            f"**Claim:** {claim.claim}",
            "",
        ]

        # Source references
        support_str = (
            " ".join(f"\\[{s}\\]" for s in claim.supporting_sources)
            if claim.supporting_sources
            else "—"
        )
        contra_str = (
            " ".join(f"\\[{c}\\]" for c in claim.contradicting_sources)
            if claim.contradicting_sources
            else "—"
        )
        lines += [
            f"| | |",
            f"|---|---|",
            f"| **Supporting sources** | {support_str} |",
            f"| **Contradicting sources** | {contra_str} |",
            "",
        ]

        # Conflict callout
        if claim.status == "Conflicting" and claim.conflict_explanation:
            lines += [
                "> [!WARNING]",
                f"> **Conflict Detected:** {claim.conflict_explanation}",
                "",
            ]

        # Evidence quotes
        if claim.evidence_quotes:
            lines.append("**Evidence:**")
            lines.append("")
            for quote in claim.evidence_quotes:
                lines.append(f"- {quote}")
            lines.append("")

    lines += ["---", ""]

    # ── Research Timeline ────────────────────────────────────────────────────
    if report.timeline:
        timeline_sorted = sorted(report.timeline, key=lambda e: e.date)
        lines += [
            "## Research Timeline",
            "",
            "| Date | Event | Source |",
            "|:-----|:------|:------:|",
        ]
        for event in timeline_sorted:
            event_text = event.event.replace("|", "\\|")
            lines.append(f"| {event.date} | {event_text} | \\[{event.source_id}\\] |")
        lines += ["", "---", ""]

    # ── Follow-Up Questions ──────────────────────────────────────────────────
    if report.follow_up_questions:
        lines += [
            "## Follow-Up Research Questions",
            "",
        ]
        for i, q in enumerate(report.follow_up_questions, 1):
            lines.append(f"{i}. {q}")
        lines += ["", "---", ""]

    # ── Bibliography ─────────────────────────────────────────────────────────
    lines += [
        "## Bibliography",
        "",
    ]
    for src in sorted(sources, key=lambda s: s.source_id):
        date_str = f" ({src.published_date})" if src.published_date else ""
        lines += [
            f"**\\[{src.source_id}\\]** {src.title}{date_str}  ",
            f"URL: <{src.url}>  ",
            f"Domain: `{src.domain}` · Retrieval: `{src.retrieval_method}`  ",
            "",
        ]

    lines += [
        "---",
        "",
        "*Generated by **ResearchMesh** — powered by [TinyFish](https://tinyfish.ai)"
        " & [Google Gemini](https://deepmind.google/technologies/gemini/).*",
    ]

    return "\n".join(lines)


def to_json(report: ResearchReport, sources: List[SourceReference]) -> str:
    """
    Serialize the full structured evidence bundle to indented JSON.

    The output contains both the ResearchReport and the SourceReference list
    so downstream tools have everything needed to reconstruct the report.
    """
    bundle = {
        "report": report.model_dump(mode="json"),
        "sources": [s.model_dump(mode="json") for s in sources],
        "_meta": {
            "generator": "ResearchMesh v1.0",
            "source_count": len(sources),
            "claim_count": len(report.claims),
            "timeline_event_count": len(report.timeline),
        },
    }
    return json.dumps(bundle, indent=2, ensure_ascii=False)
